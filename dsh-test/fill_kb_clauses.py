def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    shutil.copyfile(SRC, BAK)
    missing = []
    for row in data:
        kid = row.get("kb_id")
        if kid in M:
            cno, ctext, note = M[kid]
            row["clause_no"] = cno
            row["clause_text"] = ctext
            if note:
                row["standard"] = (row.get("standard", "") + "；" + note).strip("；")
        else:
            missing.append(kid)
    SRC.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("updated", len(data) - len(missing), "missing", missing)
    print("backup", BAK)


if __name__ == "__main__":
    main()
